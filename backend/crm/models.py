class Customer(TimestampedModel):
    """
    Core customer profile.

    Scoped to company (Organization) + restaurant. A customer is identified
    within a restaurant scope — the same physical person may have separate
    customer records in different restaurants (intentional: no cross-restaurant
    merging without controlled workflow).

    Identity fields (phone, email) are normalized before matching.

    Computed statistics (total_visits, total_orders, lifetime_spend, etc.)
    are NEVER trusted from frontend input. They are updated exclusively by
    CustomerStatisticsService.

    customer_number is immutable after creation. Generated by CustomerService
    using CustomerSequence.select_for_update().
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)

    # -------------------------------------------------------------------------
    # Scope
    # -------------------------------------------------------------------------
    company = models.ForeignKey(
        "organizations.Organization",
        on_delete=models.PROTECT,
        related_name="customers",
        db_index=True,
    )
    restaurant = models.ForeignKey(
        "organizations.Restaurant",
        on_delete=models.PROTECT,
        related_name="customers",
        db_index=True,
    )

    # -------------------------------------------------------------------------
    # Identity
    # -------------------------------------------------------------------------
    customer_number = models.CharField(
        max_length=30,
        db_index=True,
        help_text="Human-readable, immutable identifier. Format: CUS-000001.",
    )

    # -------------------------------------------------------------------------
    # Personal details
    # -------------------------------------------------------------------------
    first_name = models.CharField(max_length=150, db_index=True)
    last_name = models.CharField(max_length=150, blank=True, db_index=True)
    display_name = models.CharField(
        max_length=200,
        blank=True,
        help_text="If blank, derived from first_name + last_name.",
    )
    phone = models.CharField(
        max_length=30,
        blank=True,
        db_index=True,
        help_text="Normalized E.164-style phone.",
    )
    email = models.EmailField(
        blank=True,
        db_index=True,
        help_text="Normalized lowercase email.",
    )
    date_of_birth = models.DateField(null=True, blank=True)
    gender = models.CharField(
        max_length=1,
        choices=GENDER_CHOICES,
        blank=True,
    )

    # -------------------------------------------------------------------------
    # Address
    # -------------------------------------------------------------------------
    address = models.TextField(blank=True)
    city = models.CharField(max_length=100, blank=True)
    state = models.CharField(max_length=100, blank=True)
    postal_code = models.CharField(max_length=20, blank=True)
    country = models.CharField(max_length=100, blank=True, default="India")

    # -------------------------------------------------------------------------
    # Internal notes
    # -------------------------------------------------------------------------
    notes = models.TextField(blank=True)
    preferred_language = models.CharField(max_length=10, blank=True)

    # -------------------------------------------------------------------------
    # Status
    # -------------------------------------------------------------------------
    is_active = models.BooleanField(default=True, db_index=True)
    is_blocked = models.BooleanField(default=False, db_index=True)
    blocked_reason = models.TextField(blank=True)

    # -------------------------------------------------------------------------
    # Computed statistics — NEVER set from frontend; only from services
    # -------------------------------------------------------------------------
    total_visits = models.PositiveIntegerField(default=0)
    total_orders = models.PositiveIntegerField(default=0)
    lifetime_spend = models.DecimalField(
        max_digits=14, decimal_places=2, default="0.00",
    )
    last_visit_at = models.DateTimeField(null=True, blank=True, db_index=True)
    last_order_at = models.DateTimeField(null=True, blank=True, db_index=True)
    first_order_at = models.DateTimeField(null=True, blank=True)

    # -------------------------------------------------------------------------
    # Soft-delete / merge tracking
    # -------------------------------------------------------------------------
    merged_into = models.ForeignKey(
        "self",
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
        related_name="merged_sources",
        help_text="Set when this customer was merged into another.",
    )

    class Meta:
        verbose_name = "Customer"
        verbose_name_plural = "Customers"
        ordering = ["-created_at"]
        constraints = [
            models.UniqueConstraint(
                fields=["restaurant", "customer_number"],
                name="unique_customer_number_per_restaurant",
            ),
        ]
        indexes = [
            models.Index(fields=["company", "restaurant"]),
            models.Index(fields=["restaurant", "is_active"]),
            models.Index(fields=["restaurant", "is_blocked"]),
            models.Index(fields=["restaurant", "created_at"]),
            models.Index(fields=["phone"]),
            models.Index(fields=["email"]),
            models.Index(fields=["last_order_at"]),
            models.Index(fields=["last_visit_at"]),
            models.Index(fields=["is_active", "is_blocked"]),
            models.Index(fields=["company", "phone"]),
            models.Index(fields=["restaurant", "phone"]),
            models.Index(fields=["restaurant", "email"]),
        ]

    def __str__(self):
        return f"{self.customer_number} — {self.effective_display_name}"

    @property
    def effective_display_name(self) -> str:
        if self.display_name:
            return self.display_name
        full = f"{self.first_name} {self.last_name}".strip()
        return full or self.customer_number

    @property
    def masked_phone(self) -> str:
        if not self.phone:
            return ""
        return f"******{self.phone[-4:]}" if len(self.phone) > 4 else "****"

    @property
    def masked_email(self) -> str:
        if not self.email:
            return ""
        parts = self.email.split("@")
        if len(parts) != 2:
            return "****"
        local, domain = parts
        masked_local = local[0] + "*" * (len(local) - 1) if local else "*"
        return f"{masked_local}@{domain}"


