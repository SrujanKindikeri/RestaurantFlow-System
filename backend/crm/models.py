class CRMAuditLog(TimestampedModel):
    """
    Immutable append-only audit trail for CRM actions.

    Pattern follows existing per-domain audit logs (PaymentAuditLog,
    FinancialAuditLog, CentralControlAuditLog).

    Never log: passwords, auth tokens, payment card data, provider secrets.
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)

    actor = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.PROTECT,
        null=True,
        blank=True,
        related_name="crm_audit_entries",
        help_text="User who performed the action. Null for system actions.",
    )
    action = models.CharField(
        max_length=60,
        choices=AUDIT_EVENT_CHOICES,
        db_index=True,
    )

    # What was acted on
    entity_type = models.CharField(max_length=50, db_index=True)
    entity_id = models.UUIDField(null=True, blank=True, db_index=True)

    # Scope
    company = models.ForeignKey(
        "organizations.Organization",
        on_delete=models.PROTECT,
        null=True, blank=True,
        related_name="crm_audit_logs",
        db_index=True,
    )
    restaurant = models.ForeignKey(
        "organizations.Restaurant",
        on_delete=models.PROTECT,
        null=True, blank=True,
        related_name="crm_audit_logs",
    )
    branch = models.ForeignKey(
        "organizations.Branch",
        on_delete=models.PROTECT,
        null=True, blank=True,
        related_name="crm_audit_logs",
    )
    customer = models.ForeignKey(
        Customer,
        on_delete=models.SET_NULL,
        null=True, blank=True,
        related_name="audit_logs",
        db_index=True,
    )

    metadata = models.JSONField(
        default=dict,
        blank=True,
        help_text="Structured data about the action. Never include PII unnecessarily.",
    )

    class Meta:
        verbose_name = "CRM Audit Log"
        verbose_name_plural = "CRM Audit Logs"
        ordering = ["-created_at"]
        indexes = [
            models.Index(fields=["actor", "created_at"]),
            models.Index(fields=["action", "created_at"]),
            models.Index(fields=["entity_type", "entity_id"]),
            models.Index(fields=["company", "created_at"]),
            models.Index(fields=["customer", "created_at"]),
        ]

    def __str__(self):
        return f"CRMAudit: {self.action} on {self.entity_type}:{self.entity_id}"

    def save(self, *args, **kwargs):
        if self.pk and CRMAuditLog.objects.filter(pk=self.pk).exists():
            raise ValueError("CRMAuditLog records are immutable.")
        super().save(*args, **kwargs)
