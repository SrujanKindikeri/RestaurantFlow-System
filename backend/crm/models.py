class LoyaltyTransaction(TimestampedModel):
    """
    Immutable ledger entry for every loyalty balance change.

    Never edit an existing transaction. Every balance change MUST:
      1. Create a LoyaltyTransaction
      2. Update LoyaltyAccount.points_balance

    Both steps happen inside transaction.atomic() with select_for_update().

    reference_type + reference_id are used for idempotency:
      - BILL:<bill_uuid> prevents double-awarding from the same bill
      - REDEMPTION:<redemption_uuid> links to a RewardRedemption

    Balance integrity:
        balance_before + points (signed) == balance_after
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)

    loyalty_account = models.ForeignKey(
        LoyaltyAccount,
        on_delete=models.PROTECT,
        related_name="transactions",
        db_index=True,
    )
    transaction_type = models.CharField(
        max_length=20,
        choices=LOYALTY_TRANSACTION_TYPE_CHOICES,
        db_index=True,
    )

    # Signed: positive for EARN/BONUS, negative for REDEEM/EXPIRY/REVERSAL
    points = models.IntegerField()

    balance_before = models.PositiveIntegerField()
    balance_after = models.PositiveIntegerField()

    reference_type = models.CharField(max_length=50, blank=True, db_index=True)
    reference_id = models.CharField(max_length=100, blank=True, db_index=True)

    reason = models.TextField(blank=True)

    created_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.PROTECT,
        null=True,
        blank=True,
        related_name="loyalty_transactions_created",
    )

    class Meta:
        verbose_name = "Loyalty Transaction"
        verbose_name_plural = "Loyalty Transactions"
        ordering = ["-created_at"]
        constraints = [
            models.UniqueConstraint(
                fields=["loyalty_account", "reference_type", "reference_id"],
                condition=~models.Q(reference_type=""),
                name="unique_loyalty_transaction_per_reference",
            ),
        ]
        indexes = [
            models.Index(fields=["loyalty_account", "created_at"]),
            models.Index(fields=["reference_type", "reference_id"]),
            models.Index(fields=["transaction_type", "created_at"]),
        ]

    def __str__(self):
        return (
            f"LoyaltyTxn [{self.transaction_type}] "
            f"pts={self.points:+d} bal={self.balance_after} "
            f"ref={self.reference_type}:{self.reference_id}"
        )

    def save(self, *args, **kwargs):
        """LoyaltyTransactions are append-only — block updates."""
        if self.pk and LoyaltyTransaction.objects.filter(pk=self.pk).exists():
            raise ValueError(
                "LoyaltyTransaction records are immutable — they cannot be updated."
            )
        super().save(*args, **kwargs)


