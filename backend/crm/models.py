class RewardRedemption(TimestampedModel):
    """
    Record of a customer redeeming a LoyaltyReward.

    Points are deducted atomically via LoyaltyService. The redemption record
    is created in the same transaction as the LoyaltyTransaction(REDEEM).

    reference_code is a short human-readable code for POS use.
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)

    customer = models.ForeignKey(
        Customer,
        on_delete=models.PROTECT,
        related_name="reward_redemptions",
        db_index=True,
    )
    loyalty_account = models.ForeignKey(
        LoyaltyAccount,
        on_delete=models.PROTECT,
        related_name="redemptions",
        db_index=True,
    )
    reward = models.ForeignKey(
        LoyaltyReward,
        on_delete=models.PROTECT,
        related_name="redemptions",
        db_index=True,
    )

    points_used = models.PositiveIntegerField()

    status = models.CharField(
        max_length=20,
        choices=REDEMPTION_STATUS_CHOICES,
        default=REDEMPTION_REQUESTED,
        db_index=True,
    )
    reference_code = models.CharField(
        max_length=20,
        blank=True,
        db_index=True,
        help_text="Short code for POS/cashier use.",
    )

    redeemed_at = models.DateTimeField(null=True, blank=True)
    expires_at = models.DateTimeField(null=True, blank=True)

    # Optional link to an order/bill where this reward was applied
    applied_to_order = models.ForeignKey(
        "orders.Order",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="reward_redemptions",
    )

    class Meta:
        verbose_name = "Reward Redemption"
        verbose_name_plural = "Reward Redemptions"
        ordering = ["-created_at"]
        indexes = [
            models.Index(fields=["customer", "status"]),
            models.Index(fields=["reward", "status"]),
            models.Index(fields=["reference_code"]),
            models.Index(fields=["expires_at"]),
        ]

    def __str__(self):
        return (
            f"Redemption {self.reference_code or self.pk} — "
            f"{self.customer.customer_number} [{self.status}]"
        )


