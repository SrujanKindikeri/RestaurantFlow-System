class CustomerMergeRequest(TimestampedModel):
    """
    Controlled merge workflow: source customer → target customer.

    Merge requires approval from an authorized user.
    After approval, source customer is deactivated and its history
    is reassigned to the target (via CustomerMergeService).

    Never auto-approve merges. Always require explicit approval.
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)

    source_customer = models.ForeignKey(
        Customer,
        on_delete=models.PROTECT,
        related_name="merge_requests_as_source",
        db_index=True,
    )
    target_customer = models.ForeignKey(
        Customer,
        on_delete=models.PROTECT,
        related_name="merge_requests_as_target",
        db_index=True,
    )
    requested_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.PROTECT,
        related_name="merge_requests_made",
    )
    approved_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.PROTECT,
        null=True,
        blank=True,
        related_name="merge_requests_approved",
    )
    status = models.CharField(
        max_length=20,
        choices=MERGE_STATUS_CHOICES,
        default=MERGE_REQUESTED,
        db_index=True,
    )
    reason = models.TextField()
    notes = models.TextField(blank=True)

    approved_at = models.DateTimeField(null=True, blank=True)
    rejected_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        verbose_name = "Customer Merge Request"
        verbose_name_plural = "Customer Merge Requests"
        ordering = ["-created_at"]
        indexes = [
            models.Index(fields=["source_customer", "status"]),
            models.Index(fields=["target_customer", "status"]),
            models.Index(fields=["status", "created_at"]),
        ]

    def __str__(self):
        return (
            f"MergeRequest {self.source_customer.customer_number} → "
            f"{self.target_customer.customer_number} [{self.status}]"
        )


