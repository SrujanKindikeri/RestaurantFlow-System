class CustomerFeedback(TimestampedModel):
    """
    Customer rating and comment for an order/visit.

    Ratings are integers 1–5. All four rating fields (overall, service,
    food, ambience) are optional except the top-level `rating`.

    If linked to an order, the service validates ownership and eligibility.
    Anonymous feedback is supported (customer = null, order = null).
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)

    customer = models.ForeignKey(
        Customer,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="feedback",
        db_index=True,
    )
    restaurant = models.ForeignKey(
        "organizations.Restaurant",
        on_delete=models.PROTECT,
        related_name="customer_feedback",
        db_index=True,
    )
    branch = models.ForeignKey(
        "organizations.Branch",
        on_delete=models.PROTECT,
        null=True,
        blank=True,
        related_name="customer_feedback",
        db_index=True,
    )
    order = models.OneToOneField(
        "orders.Order",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="customer_feedback",
    )
    visit = models.ForeignKey(
        CustomerVisit,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="feedback",
    )

    rating = models.PositiveSmallIntegerField(
        validators=[MinValueValidator(1), MaxValueValidator(5)],
        help_text="Overall rating 1–5.",
    )
    service_rating = models.PositiveSmallIntegerField(
        null=True, blank=True,
        validators=[MinValueValidator(1), MaxValueValidator(5)],
    )
    food_rating = models.PositiveSmallIntegerField(
        null=True, blank=True,
        validators=[MinValueValidator(1), MaxValueValidator(5)],
    )
    ambience_rating = models.PositiveSmallIntegerField(
        null=True, blank=True,
        validators=[MinValueValidator(1), MaxValueValidator(5)],
    )

    comment = models.TextField(blank=True)

    status = models.CharField(
        max_length=20,
        choices=FEEDBACK_STATUS_CHOICES,
        default=FEEDBACK_SUBMITTED,
        db_index=True,
    )

    class Meta:
        verbose_name = "Customer Feedback"
        verbose_name_plural = "Customer Feedback"
        ordering = ["-created_at"]
        indexes = [
            models.Index(fields=["restaurant", "status"]),
            models.Index(fields=["restaurant", "rating"]),
            models.Index(fields=["branch", "status"]),
            models.Index(fields=["customer", "created_at"]),
            models.Index(fields=["created_at"]),
        ]

    def __str__(self):
        cnum = self.customer.customer_number if self.customer else "anon"
        return f"Feedback {self.rating}/5 — {cnum} [{self.status}]"


