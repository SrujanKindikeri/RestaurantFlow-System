class LoyaltyReward(TimestampedModel):
    """
    Reward definitions that customers can redeem with their loyalty points.

    Rewards are restaurant-scoped definitions. Actual redemption records are
    in RewardRedemption.
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)

    restaurant = models.ForeignKey(
        "organizations.Restaurant",
        on_delete=models.PROTECT,
        related_name="loyalty_rewards",
        db_index=True,
    )
    name = models.CharField(max_length=200)
    description = models.TextField(blank=True)

    reward_type = models.CharField(
        max_length=20,
        choices=REWARD_TYPE_CHOICES,
        db_index=True,
    )
    points_required = models.PositiveIntegerField(
        validators=[MinValueValidator(1)],
    )

    # For DISCOUNT / PERCENTAGE reward types
    reward_value = models.DecimalField(
        max_digits=10, decimal_places=2,
        null=True, blank=True,
    )
    discount_type = models.CharField(max_length=20, blank=True)
    discount_value = models.DecimalField(
        max_digits=10, decimal_places=2,
        null=True, blank=True,
    )
    max_discount_amount = models.DecimalField(
        max_digits=10, decimal_places=2,
        null=True, blank=True,
    )

    is_active = models.BooleanField(default=True, db_index=True)
    valid_from = models.DateTimeField(null=True, blank=True)
    valid_until = models.DateTimeField(null=True, blank=True)

    class Meta:
        verbose_name = "Loyalty Reward"
        verbose_name_plural = "Loyalty Rewards"
        ordering = ["points_required"]
        indexes = [
            models.Index(fields=["restaurant", "is_active"]),
            models.Index(fields=["valid_until"]),
        ]

    def __str__(self):
        return f"{self.name} ({self.points_required} pts) [{self.restaurant.name}]"


