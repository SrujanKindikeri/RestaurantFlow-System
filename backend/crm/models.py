class CustomerConsent(TimestampedModel):
    """
    Customer communication consent record.

    One row per customer+consent_type — the current consent state.
    History is preserved in CustomerConsentHistory.

    Marketing communications require explicit GRANTED consent.
    Transactional notifications do not require marketing consent.
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)

    customer = models.ForeignKey(
        Customer,
        on_delete=models.CASCADE,
        related_name="consents",
        db_index=True,
    )
    consent_type = models.CharField(
        max_length=40,
        choices=CONSENT_TYPE_CHOICES,
        db_index=True,
    )
    status = models.CharField(
        max_length=20,
        choices=CONSENT_STATUS_CHOICES,
        db_index=True,
    )
    source = models.CharField(
        max_length=20,
        choices=CONSENT_SOURCE_CHOICES,
        default="CUSTOMER",
    )
    granted_at = models.DateTimeField(null=True, blank=True)
    revoked_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        verbose_name = "Customer Consent"
        verbose_name_plural = "Customer Consents"
        constraints = [
            models.UniqueConstraint(
                fields=["customer", "consent_type"],
                name="unique_consent_per_customer_type",
            ),
        ]
        indexes = [
            models.Index(fields=["customer", "status"]),
            models.Index(fields=["consent_type", "status"]),
        ]

    def __str__(self):
        return (
            f"Consent {self.consent_type} [{self.status}] "
            f"— {self.customer.customer_number}"
        )


