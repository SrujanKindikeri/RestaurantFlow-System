class CustomerConsentHistory(TimestampedModel):
    """
    Immutable audit trail for consent changes.

    Created every time a CustomerConsent is updated.
    Never edit or delete these records.
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)

    customer = models.ForeignKey(
        Customer,
        on_delete=models.CASCADE,
        related_name="consent_history",
        db_index=True,
    )
    consent_type = models.CharField(max_length=40, choices=CONSENT_TYPE_CHOICES)
    previous_status = models.CharField(max_length=20, blank=True)
    new_status = models.CharField(max_length=20, choices=CONSENT_STATUS_CHOICES)
    changed_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.PROTECT,
        null=True,
        blank=True,
        related_name="consent_changes_made",
    )
    source = models.CharField(max_length=20, choices=CONSENT_SOURCE_CHOICES)
    changed_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name = "Customer Consent History"
        verbose_name_plural = "Customer Consent Histories"
        ordering = ["-changed_at"]
        indexes = [
            models.Index(fields=["customer", "changed_at"]),
            models.Index(fields=["consent_type", "changed_at"]),
        ]

    def __str__(self):
        return (
            f"ConsentHistory {self.consent_type} "
            f"{self.previous_status}→{self.new_status} "
            f"@ {self.changed_at}"
        )

    def save(self, *args, **kwargs):
        if self.pk and CustomerConsentHistory.objects.filter(pk=self.pk).exists():
            raise ValueError("CustomerConsentHistory records are immutable.")
        super().save(*args, **kwargs)


