class CustomerSequence(TimestampedModel):
    """
    Concurrency-safe customer number sequence per restaurant.

    Format: CUS-{seq:06d}

    Uses select_for_update() in the service — never MAX()+1.
    One row per restaurant.
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)

    restaurant = models.OneToOneField(
        "organizations.Restaurant",
        on_delete=models.PROTECT,
        related_name="customer_sequence",
        db_index=True,
    )

    last_sequence = models.PositiveIntegerField(default=0)

    class Meta:
        verbose_name = "Customer Sequence"
        verbose_name_plural = "Customer Sequences"

    def __str__(self):
        return f"CustomerSeq restaurant={self.restaurant.name} seq={self.last_sequence}"


