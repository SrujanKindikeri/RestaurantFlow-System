class CustomerVisit(TimestampedModel):
    """
    Tracks a single customer visit to a restaurant branch.

    Idempotency: keyed on `order` — one qualifying order produces at most
    one CustomerVisit. The service checks for an existing visit before creating.

    Do NOT create visits for DRAFT or CANCELLED orders.
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)

    customer = models.ForeignKey(
        Customer,
        on_delete=models.CASCADE,
        related_name="visits",
        db_index=True,
    )
    restaurant = models.ForeignKey(
        "organizations.Restaurant",
        on_delete=models.PROTECT,
        related_name="customer_visits",
        db_index=True,
    )
    branch = models.ForeignKey(
        "organizations.Branch",
        on_delete=models.PROTECT,
        related_name="customer_visits",
        db_index=True,
    )

    # Idempotency reference — one order = at most one visit
    order = models.OneToOneField(
        "orders.Order",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="customer_visit",
    )
    table_session = models.ForeignKey(
        "orders.TableSession",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="customer_visits",
    )

    visit_number = models.PositiveIntegerField(
        default=1,
        help_text="Sequential visit number for this customer at this restaurant.",
    )
    visit_started_at = models.DateTimeField(db_index=True)
    visit_completed_at = models.DateTimeField(null=True, blank=True)
    guest_count = models.PositiveIntegerField(default=1)

    visit_type = models.CharField(
        max_length=20,
        choices=VISIT_TYPE_CHOICES,
        db_index=True,
    )
    status = models.CharField(
        max_length=20,
        choices=VISIT_STATUS_CHOICES,
        default=VISIT_OPEN,
        db_index=True,
    )

    class Meta:
        verbose_name = "Customer Visit"
        verbose_name_plural = "Customer Visits"
        ordering = ["-visit_started_at"]
        indexes = [
            models.Index(fields=["customer", "restaurant"]),
            models.Index(fields=["customer", "visit_started_at"]),
            models.Index(fields=["branch", "visit_started_at"]),
            models.Index(fields=["restaurant", "status"]),
        ]

    def __str__(self):
        return (
            f"Visit #{self.visit_number} — {self.customer.customer_number} "
            f"@ {self.branch.name} [{self.status}]"
        )


