# =============================================================================
# RestaurantFlow — CRM Models
# Phase 17: Customer Management, CRM, Loyalty & Feedback
#
# Models:
#   CustomerSequence          — concurrency-safe customer number generator
#   Customer                  — core customer profile (company + restaurant scoped)
#   CustomerPreference        — customer-provided preferences
#   CustomerVisit             — visit tracking (idempotent, order-referenced)
#   CustomerTag               — restaurant-defined tags
#   CustomerTagAssignment     — customer ↔ tag assignment
#   CustomerSegment           — criteria-based segmentation definitions
#   CustomerSegmentAssignment — customer ↔ segment assignment with audit snapshot
#   LoyaltyProgram            — restaurant-scoped loyalty program
#   LoyaltyAccount            — per-customer loyalty balance
#   LoyaltyTransaction        — immutable ledger (EARN/REDEEM/BONUS/ADJUSTMENT/EXPIRY/REVERSAL)
#   LoyaltyReward             — reward definitions
#   RewardRedemption          — redemption records
#   CustomerFeedback          — customer ratings and comments
#   FeedbackModeration        — moderation workflow for feedback
#   CustomerConsent           — customer communication consent records
#   CustomerConsentHistory    — immutable consent history
#   CustomerMergeRequest      — controlled merge approval workflow
#   CRMAuditLog               — append-only audit trail for CRM actions
#
# Design principles:
#   - UUID primary keys on all business models.
#   - TimestampedModel base for created_at / updated_at.
#   - PROTECT foreign keys — no accidental cascade deletion.
#   - All monetary values use DecimalField — never float.
#   - Loyalty balance changes are ONLY made through the service layer.
#   - Audit logs are immutable (save() guard like existing apps).
#   - Company / restaurant / branch scope enforced in service layer.
#   - Never duplicate Order / Bill / Payment models.
# =============================================================================

